// English / Bahasa Indonesia strings for AngkaBangsa.
// Data objects carry bilingual fields (e.g. title + titleId); pick() selects.

export function lang() {
  return 'en';
}

export function pick(obj, base) {
  if (!obj) return '';
  if (lang() === 'id' && obj[base + 'Id']) return obj[base + 'Id'];
  return obj[base] || '';
}

